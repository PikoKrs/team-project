#include <iostream>

// === БЛОК ПОДКЛЮЧЕНИЙ: каждый участник добавляет свой заголовочный файл ===
#include "maksimov.h"
#include "burbach.h"
#include "krivov.h"
// === КОНЕЦ БЛОКА ПОДКЛЮЧЕНИЙ ===

using namespace std;

int main() {
    int choice;

    do {
        cout << "\n=== Командный проект: сборник расчётов ===\n";
        // === БЛОК МЕНЮ: каждый участник добавляет свои пункты ===
        cout << "1. Сила тока (закон Ома)\n";
        cout << "2. Сопротивление проводника\n";
        cout << "3. Мощность тока\n";
        cout << "4. Килограммы -> фунты\n";
        cout << "5. Фунты -> килограммы\n";
        cout << "6. Будущая цена товара (инфляция)\n";
        cout << "7. Покупательная способность денег\n";
        // === КОНЕЦ БЛОКА МЕНЮ ===
        cout << "0. Выход\n";
        cout << "Выберите пункт: ";
        cin >> choice;

        switch (choice) {
            // === БЛОК ОБРАБОТКИ: каждый участник добавляет свои case ===
            case 1: {
                double U, R;
                cout << "Введите напряжение U (В) и сопротивление R (Ом): ";
                cin >> U >> R;
                if (R <= 0) {
                    cout << "Ошибка: сопротивление должно быть положительным.\n";
                    break;
                }
                cout << "Сила тока I = " << current(U, R) << " А\n";
                break;
            }
            case 2: {
                double U, I;
                cout << "Введите напряжение U (В) и силу тока I (А): ";
                cin >> U >> I;
                if (I == 0) {
                    cout << "Ошибка: сила тока не может быть равна нулю.\n";
                    break;
                }
                cout << "Сопротивление R = " << resistance(U, I) << " Ом\n";
                break;
            }
            case 3: {
                double U, I;
                cout << "Введите напряжение U (В) и силу тока I (А): ";
                cin >> U >> I;
                cout << "Мощность P = " << electricPower(U, I) << " Вт\n";
                break;
            }
            case 4: {
                double kg;
                cout << "Введите массу в килограммах: ";
                cin >> kg;
                cout << kg << " кг = " << kgToLb(kg) << " фунтов\n";
                break;
            }
            case 5: {
                double lb;
                cout << "Введите массу в фунтах: ";
                cin >> lb;
                cout << lb << " фунтов = " << lbToKg(lb) << " кг\n";
                break;
            }
            case 6: {
                double price, inf;
                int n;
                cout << "Введите текущую цену (руб.), инфляцию (% в год) и срок (лет): ";
                cin >> price >> inf >> n;
                cout << "Будущая цена = " << futurePrice(price, inf, n) << " руб.\n";
                break;
            }
            case 7: {
                double sum, inf;
                int n;
                cout << "Введите сумму (руб.), инфляцию (% в год) и срок (лет): ";
                cin >> sum >> inf >> n;
                cout << "Покупательная способность = " << purchasingPower(sum, inf, n) << " руб.\n";
                break;
            }
            // === КОНЕЦ БЛОКА ОБРАБОТКИ ===
            case 0:
                cout << "Работа завершена.\n";
                break;
            default:
                cout << "Такого пункта нет.\n";
        }
    } while (choice != 0);

    return 0;
}
