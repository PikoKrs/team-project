using namespace std;

int main() {
    int choice;

    do {
        cout << "\n=== Командный проект: сборник расчётов ===\n";
        // === БЛОК МЕНЮ: каждый участник добавляет свои пункты ===
        cout << "1. Сила тока (закон Ома)\n";
        cout << "2. Сопротивление проводника\n";
        cout << "3. Мощность тока\n";
        // === КОНЕЦ БЛОКА МЕНЮ ===
        cout << "0. Выход\n";
        cout << "Выберите пункт: ";
        cin >> choice;

        switch (choice) {
            // === БЛОК ОБРАБОТКИ: каждый участник добавляет свои case ===
            case 1: {
                double U, R;
                cout << "Введите напряжение U (В) и сопротивление R (Ом): ";
                cin >> U >> R;
                if (R <= 0) {
                    cout << "Ошибка: сопротивление должно быть положительным.\n";
                    break;
                }
                cout << "Сила тока I = " << current(U, R) << " А\n";
                break;
            }
            case 2: {
                double U, I;
                cout << "Введите напряжение U (В) и силу тока I (А): ";
                cin >> U >> I;
                if (I == 0) {
                    cout << "Ошибка: сила тока не может быть равна нулю.\n";
                    break;
                }
                cout << "Сопротивление R = " << resistance(U, I) << " Ом\n";
                break;
            }
            case 3: {
                double U, I;
                cout << "Введите напряжение U (В) и силу тока I (А): ";
                cin >> U >> I;
                cout << "Мощность P = " << electricPower(U, I) << " Вт\n";
                break;
            }
            // === КОНЕЦ БЛОКА ОБРАБОТКИ ===
            case 0:
                cout << "Работа завершена.\n";
                break;
            default:
                cout << "Такого пункта нет.\n";
        }
    } while (choice != 0);

    return 0;
}
